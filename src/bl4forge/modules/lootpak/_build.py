"""The build pipeline: hash inputs -> plan -> set-bits -> wrap -> copy inventory -> mkpak -> extract + decode ->
decode-diff gate -> manifest + generated REGEN.txt.

The gate is the safety net under everything: the built pak is unpacked and decoded again, and the difference
from the base decode must be EXACTLY the planned lines. One extra changed line, one missing one, or a changed
value that is not the planned one, fails the build (the pak is renamed `.REJECTED` and no manifest is written).
"""
from __future__ import annotations

import json
import shutil
import tempfile
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable, Dict, List, Optional, Sequence, Tuple

from ...core.errors import LootPakError
from ._config import INVENTORY_NCS, NCS_DIR, TABLE0_NCS, LootConfig
from ._decode import diff_lines, normalise
from ._guard import check_out_dir, ensure_inside
from ._plan import Change, Plan, format_plan, make_plan
from ._tools import Tools, file_sha256

Log = Callable[[str], None]


@dataclass
class BuildResult:
    out_dir: Path
    pak_path: Path
    pak_sha256: str
    pak_bytes: int
    raw_sha256: str
    manifest_path: Path
    regen_path: Path
    plan: Plan
    diff: List[Tuple[int, str, str]] = field(default_factory=list)


def gate_problems(plan: Plan, built_decode: str) -> Tuple[List[str], List[Tuple[int, str, str]]]:
    """Compare the built decode with the base decode. Returns (problems, the changed lines)."""
    try:
        changed = diff_lines(plan.base_decode, built_decode)
    except LootPakError as ex:
        return [str(ex)], []
    expected: Dict[int, Change] = {c.line: c for c in plan.changes}
    problems: List[str] = []
    seen = set()
    for no, old, new in changed:
        seen.add(no)
        c = expected.get(no)
        if c is None:
            problems.append("UNPLANNED change at decode line %d: %r -> %r" % (no + 1, old.strip(), new.strip()))
        elif old != c.old_line or new != c.new_line:
            problems.append("decode line %d (%s) is %r -> %r, planned %r -> %r"
                            % (no + 1, c.label, old.strip(), new.strip(), c.old_line.strip(), c.new_line.strip()))
    for no, c in expected.items():
        if no not in seen:
            problems.append("planned change did not happen: %s (decode line %d)" % (c.label, no + 1))
    return problems, changed


def _hash_inputs(config: LootConfig) -> Dict[str, Dict[str, object]]:
    out: Dict[str, Dict[str, object]] = {}
    for key, path, want in (("raw", config.base.raw, config.base.raw_sha256),
                            ("inventory", config.base.inventory, config.base.inventory_sha256),
                            ("reference_pak", config.base.reference_pak, config.base.reference_pak_sha256)):
        if not Path(path).is_file():
            raise LootPakError("base input not found: %s (%s)" % (path, key))
        sha = file_sha256(Path(path))
        if want and want != sha:
            raise LootPakError("base %s sha256 mismatch: config says %s, file is %s" % (key, want, sha))
        out[key] = {"path": str(Path(path).resolve()), "sha256": sha, "bytes": Path(path).stat().st_size}
    return out


def _fwd(p: object) -> str:
    return str(p).replace("\\", "/")


def regen_text(config: LootConfig, plan: Plan, inputs: Dict, outputs: Dict, tool_paths: Dict[str, str],
               out: Path, raw_out: Path, table_ncs: Path, inv_ncs: Path, ex_dir: Path, decoded: Path) -> str:
    n_dir = NCS_DIR
    lines = [
        "%s: generated by bl4forge lootpak-build; VALUE RETARGETS ONLY (set_leaf), no inserts, no new pool strings."
        % config.name,
        "From a Git Bash shell. This file is the recipe for the same pak; the tool ran exactly these steps.",
        "T=%s ; B=%s ; U=%s ; N=%s" % (_fwd(tool_paths.get("ncstool", "ncstool")), _fwd(tool_paths.get("bl4", "bl4")),
                                         _fwd(tool_paths.get("uextract", "uextract")), n_dir),
        "base raw  %s  sha256 %s" % (_fwd(inputs["raw"]["path"]), inputs["raw"]["sha256"]),
        "base inv  %s  sha256 %s" % (_fwd(inputs["inventory"]["path"]), inputs["inventory"]["sha256"]),
        "ref pak   %s  sha256 %s" % (_fwd(inputs["reference_pak"]["path"]), inputs["reference_pak"]["sha256"]),
        "BINOFF %d. set-bits args = bitpos bits OLD NEW (pool indexes of the value strings)." % plan.binoff,
    ]
    for c in plan.changes:
        lines.append("  %d %d %d %d    # %s  %s -> %s" % (c.bitpos, c.bits, c.old_index, c.new_index, c.label,
                                                          c.old_text, c.new_text))
    for lab in plan.unchanged:
        lines.append("  (unchanged: %s)" % lab)
    triples = " ".join("%d %d %d %d" % c.triple for c in plan.changes)
    if plan.changes:
        lines.append("$T set-bits %s %s %d %s" % (_fwd(config.base.raw), _fwd(raw_out), plan.binoff, triples))
    else:
        lines.append("cp %s %s    # empty plan: the base table unchanged" % (_fwd(config.base.raw), _fwd(raw_out)))
    lines.append("$T wrap %s %s" % (_fwd(raw_out), _fwd(table_ncs)))
    lines.append("cp %s %s" % (_fwd(config.base.inventory), _fwd(inv_ncs)))
    lines.append("$T mkpak %s %s %s %s $N/%s=%s $N/%s=%s" % (
        _fwd(out / config.pak.name), config.pak.mount, "none" if config.pak.seed is None else config.pak.seed,
        _fwd(config.base.reference_pak), TABLE0_NCS, _fwd(table_ncs), INVENTORY_NCS, _fwd(inv_ncs)))
    lines.append("$U pak %s -o %s ; $B ncs show <extracted %s> > %s" % (
        _fwd(out / config.pak.name), _fwd(ex_dir), TABLE0_NCS, _fwd(decoded)))
    lines.append("diff vs the base decode: %d line(s) out, %d in, exactly the changes above" % (
        len(plan.changes), len(plan.changes)))
    lines.append("sha256 %s  size %d" % (outputs["pak"]["sha256"], outputs["pak"]["bytes"]))
    return "\n".join(lines) + "\n"


def build(config: LootConfig, out_dir: Path, tools: Tools, log: Log = lambda s: None,
          protected: Sequence[Path] = ()) -> BuildResult:
    inputs_paths = [config.base.raw, config.base.inventory, config.base.reference_pak]
    out = check_out_dir(Path(out_dir), inputs_paths, protected)          # refuse BEFORE doing anything
    inputs = _hash_inputs(config)
    log("inputs hashed: raw %s  inventory %s  reference pak %s" % (
        inputs["raw"]["sha256"][:12], inputs["inventory"]["sha256"][:12], inputs["reference_pak"]["sha256"][:12]))
    with tempfile.TemporaryDirectory(prefix="lootpak-plan-") as scratch:
        plan = make_plan(config, tools, Path(scratch))
    for line in format_plan(plan):                                     # the plan is printed before any write
        log(line)

    out.mkdir(parents=True, exist_ok=False)
    w = out / "work"
    t0_dir = out / "in" / "t0" / NCS_DIR
    inv_dir = out / "in" / "inv" / NCS_DIR
    ex_dir = out / "ex"
    for d in (w, t0_dir, inv_dir):
        ensure_inside(out, d).mkdir(parents=True, exist_ok=True)
    raw_out = ensure_inside(out, w / ("t0_%s.raw" % config.name))
    table_ncs = ensure_inside(out, t0_dir / TABLE0_NCS)
    inv_ncs = ensure_inside(out, inv_dir / INVENTORY_NCS)
    pak = ensure_inside(out, out / config.pak.name)
    decoded = ensure_inside(out, out / "decoded_table0.txt")

    if plan.changes:
        tools.set_bits(config.base.raw, raw_out, plan.binoff, [c.triple for c in plan.changes])
    else:
        shutil.copyfile(config.base.raw, raw_out)
    tools.wrap(raw_out, table_ncs)
    shutil.copyfile(config.base.inventory, inv_ncs)
    tools.mkpak(pak, config.pak.mount, config.pak.seed, config.base.reference_pak,
                [("%s/%s" % (NCS_DIR, TABLE0_NCS), table_ncs), ("%s/%s" % (NCS_DIR, INVENTORY_NCS), inv_ncs)])

    extracted = tools.extract(pak, ex_dir)
    ex_t0 = [p for p in extracted if p.name == TABLE0_NCS]
    ex_inv = [p for p in extracted if p.name == INVENTORY_NCS]
    problems: List[str] = []
    if len(ex_t0) != 1 or len(ex_inv) != 1:
        raise _reject(pak, out, ["the built pak does not hold exactly one %s and one %s (found %d, %d)"
                                 % (TABLE0_NCS, INVENTORY_NCS, len(ex_t0), len(ex_inv))])
    built_decode = tools.decode(ex_t0[0])
    decoded.write_text(normalise(built_decode), encoding="utf-8", newline="\n")
    gate, changed = gate_problems(plan, built_decode)
    problems.extend(gate)
    if file_sha256(ex_inv[0]) != file_sha256(inv_ncs):
        problems.append("inventory_container0 inside the pak differs from the base inventory")
    if file_sha256(ex_t0[0]) != file_sha256(table_ncs):
        problems.append("table0 inside the pak differs from the wrapped table we gave mkpak")
    for key, path in (("raw", config.base.raw), ("inventory", config.base.inventory),
                      ("reference_pak", config.base.reference_pak)):
        if file_sha256(Path(path)) != inputs[key]["sha256"]:
            problems.append("BASE INPUT CHANGED during the build: %s" % path)
    if problems:
        raise _reject(pak, out, problems)

    diff_path = ensure_inside(out, out / "diff_table0_vs_base.txt")
    diff_path.write_text("".join("line %d\n- %s\n+ %s\n" % (n + 1, a, b) for n, a, b in changed),
                         encoding="utf-8", newline="\n")
    outputs = {
        "raw": {"path": str(raw_out), "sha256": file_sha256(raw_out), "bytes": raw_out.stat().st_size},
        "table0_ncs": {"path": str(table_ncs), "sha256": file_sha256(table_ncs), "bytes": table_ncs.stat().st_size},
        "inventory_ncs": {"path": str(inv_ncs), "sha256": file_sha256(inv_ncs), "bytes": inv_ncs.stat().st_size},
        "pak": {"path": str(pak), "sha256": file_sha256(pak), "bytes": pak.stat().st_size},
    }
    manifest = {
        "name": config.name, "built": time.strftime("%Y-%m-%dT%H:%M:%S"), "config": str(config.source or ""),
        "operations": ["set_leaf"], "inputs": inputs, "tools": tools.fingerprints(), "outputs": outputs,
        "binoff": plan.binoff, "plan": [c.as_dict() for c in plan.changes], "unchanged": list(plan.unchanged),
        "notes": list(plan.notes),
        "diff": [{"line": n + 1, "old": a.strip(), "new": b.strip()} for n, a, b in changed],
        "gate": "pass: diff equals the plan exactly (%d lines)" % len(changed),
        "inputs_unchanged": True,
    }
    manifest_path = ensure_inside(out, out / "manifest.json")
    manifest_path.write_text(json.dumps(manifest, indent=1), encoding="utf-8", newline="\n")
    regen_path = ensure_inside(out, out / "REGEN.txt")
    regen_path.write_text(regen_text(config, plan, inputs, outputs, dict(tools.commands()), out, raw_out,
                                     table_ncs, inv_ncs, ex_dir, decoded), encoding="utf-8", newline="\n")
    log("gate passed: %d decode line(s) changed, all planned" % len(changed))
    log("pak %s  sha256 %s  size %d" % (pak, outputs["pak"]["sha256"], outputs["pak"]["bytes"]))
    return BuildResult(out, pak, outputs["pak"]["sha256"], outputs["pak"]["bytes"], outputs["raw"]["sha256"],
                       manifest_path, regen_path, plan, changed)


def _reject(pak: Path, out: Path, problems: List[str]) -> LootPakError:
    """Mark the pak as rejected (so it cannot be installed by mistake) and build the error."""
    try:
        if pak.exists():
            pak.replace(pak.with_name(pak.name + ".REJECTED"))
        (out / "FAILED.txt").write_text("build rejected:\n" + "\n".join(problems) + "\n", encoding="utf-8")
    except OSError:
        pass
    return LootPakError("build rejected by the decode-diff gate:\n  " + "\n  ".join(problems))
