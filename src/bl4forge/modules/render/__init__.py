"""render: Present a Loadout as a self-contained HTML code sheet and a plain-text list.

Pure formatting. `html()` and `text()` take a `core.types.Loadout` and return strings; only
`write()` touches the disk. The look lives in `style.py` (one CSS constant) so a later web-UI
phase can restyle it without touching this file. Read CONTRACT.md in this directory first.


DISCLOSURE (what this code does)
  Reads: nothing. Writes: `write()` writes the HTML and text files at the paths it is given (overwriting existing files). The HTML is self-contained: no scripts, no external links; all text is escaped. Network: none. Risk: overwrites the named output files.
"""
from __future__ import annotations

import html as _html
import os
import re
from typing import Callable, List, Optional, Tuple

from ...core import vocab
from ...core.errors import ForgeError
from ...core.module import Module
from ...core.ports import RenderPort
from ...core.types import HealthCheck, HealthReport, Loadout, LoadoutItem
from .style import COPY_JS, CSS, ELEMENT_CSS_CLASS

# --------------------------------------------------------------------------------------------
# Page template. Every %(...)s slot receives already-escaped text (or markup built here).
# The import instructions are the heart of the sheet: do not reword them casually.
# --------------------------------------------------------------------------------------------
_PAGE = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>%(title)s</title>
<style>%(css)s</style>
</head>
<body>
<header class="hero"><div class="wrap">
  <p class="eyebrow">Borderlands 4 · save-editor.be import codes</p>
  <h1>%(title)s</h1>
  <p class="subtitle">%(subtitle)s</p>
  <div class="tldr"><strong>How to import each code:</strong> open the Save Editor's Item Builder, paste a serial into the <strong>decoder box</strong> &rarr; <strong>Decode &amp; Validate</strong> (confirm the name/level line) &rarr; <strong>Add to Backpack</strong>. Nothing touches your real save until you hit <strong>Overwrite Existing Save</strong>. Clear the box between items.</div>
</div></header>

%(body)s
%(notices)s
<section class="wrap">
  <h2>Quick Checklist</h2>
  <div class="steps">
    <div class="step"><span class="n"></span><div><b>Clear the decoder box</b> before pasting each new code.</div></div>
    <div class="step"><span class="n"></span><div>Always <b>Decode &amp; Validate</b> first and check the name/level line before Add to Backpack.</div></div>
    <div class="step"><span class="n"></span><div>On <b>"Error deserializing: API error: 400,"</b> the serial was mis-pasted — use the Copy button again.</div></div>
    <div class="step"><span class="n"></span><div>Nothing is saved until <b>Overwrite Existing Save</b>.</div></div>
  </div>
</section>

<footer class="wrap">Generated by BL4 Loadout Forge · codes decoded, element-matched &amp; re-leveled from the community serial database</footer>
<script>%(js)s</script>
</body>
</html>"""

_EM_TOKEN = re.compile(r"(&lt;/?em&gt;)", re.IGNORECASE)   # an ESCAPED <em> or </em>
_CONTROL = re.compile(r"[\x00-\x1f\x7f-\x9f]")             # includes \n \r \t


# --------------------------------------------------------------------------------------------
# small pure helpers
# --------------------------------------------------------------------------------------------
def _s(value: object) -> str:
    return "" if value is None else str(value)


def _esc(value: object) -> str:
    """Escape for HTML text AND attribute values (quotes included)."""
    return _html.escape(_s(value), quote=True)


def _note_html(note: str) -> str:
    """Escape a note, then let `<em>`/`</em>` (and nothing else) through, always balanced."""
    out: List[str] = []
    depth = 0
    for part in _EM_TOKEN.split(_esc(note)):
        low = part.lower()
        if low == "&lt;em&gt;":
            out.append("<em>")
            depth += 1
        elif low == "&lt;/em&gt;" and depth:
            out.append("</em>")
            depth -= 1
        else:                      # ordinary text, or a stray </em> which stays visible as text
            out.append(part)
    out.append("</em>" * depth)    # an unclosed <em> must not leak italics into the rest of the page
    return "".join(out)


def _one_line(value: object) -> str:
    """Flatten any whitespace/control characters to single spaces (text() is line-oriented)."""
    return " ".join(_CONTROL.sub(" ", _s(value)).split())


def _element(element: Optional[str]) -> Optional[Tuple[str, str]]:
    """(css class, label) for an item's vocab element, or None when there is nothing to show.

    Elements arrive as vocab names ('cryo', 'shock', ...). An unknown value is still shown
    (escaped by the caller) rather than hidden, with the neutral 'none' class.
    """
    text = _s(element).strip()
    if not text or text.upper() == "N/A":
        return None
    key = text.lower()
    return ELEMENT_CSS_CLASS.get(key, "none"), vocab.ELEMENT_LABELS.get(key, text)


def _sections(loadout: Loadout) -> Tuple[List[Tuple[str, List[LoadoutItem]]], bool]:
    """Ordered (heading, items) sections, and whether the loadout uses real groups at all.

    Order: `loadout.groups` first, then any group named only on an item (first appearance).
    Ungrouped items are never dropped: they close the sheet under 'Loadout' (no groups at all)
    or 'Other' (when some items are grouped).
    """
    items = list(loadout.items)
    order: List[str] = []
    for g in list(loadout.groups or ()) + [it.group for it in items]:
        if g and g not in order:
            order.append(g)
    by_group = {g: [] for g in order}          # type: dict
    loose: List[LoadoutItem] = []
    for it in items:
        (by_group[it.group] if it.group else loose).append(it)
    sections = [(g, by_group[g]) for g in order if by_group[g]]
    grouped = bool(sections)
    if loose:
        sections.append(("Other" if grouped else "Loadout", loose))
    return sections, grouped


# --------------------------------------------------------------------------------------------
# HTML
# --------------------------------------------------------------------------------------------
def _card(item: LoadoutItem) -> str:
    el = _element(item.element)
    badge = '<span class="badge %s">%s</span>' % (el[0], _esc(el[1])) if el else ""
    lvl = ("Lv %s" % _esc(item.level)) if item.level is not None else ""
    # The decoded category and rarity (already the "best truth" on the item) lead the sub line.
    sub = " · ".join(x for x in [_esc(item.category or item.label), _esc(item.rarity), lvl] if x)
    note = _s(item.note)
    serial = _esc(item.serial)

    extras = ""
    if item.odds:
        extras += '\n      <p class="odds">%s</p>' % _esc(item.odds)
    if item.parts:
        extras += '\n      <details class="parts"><summary>%d part%s</summary><p>%s</p></details>' % (
            len(item.parts), "" if len(item.parts) == 1 else "s",
            _esc(" · ".join(_s(p) for p in item.parts)))
    for w in item.warnings:
        extras += '\n      <p class="warn"><b>Warning</b> · %s</p>' % _esc(w)

    return """    <div class="card">
      <div class="chead">
        <div><span class="cname">%s</span> %s</div>
        <span class="ctype">%s</span>
      </div>%s%s
      <div class="serialrow">
        <code class="serial">%s</code>
        <button class="copy" onclick="cp(this)" data-s="%s">Copy</button>
      </div>
    </div>""" % (
        _esc(item.shown_name or "?"),
        badge,
        sub,
        ('\n      <p class="cnote">%s</p>' % _note_html(note)) if note else "",
        extras,
        serial, serial)


def _section(heading: str, inner: str) -> str:
    return '<section class="wrap">\n  <h2>%s</h2>\n%s\n</section>' % (_esc(heading), inner)


def _notices(loadout: Loadout) -> str:
    blocks = []
    for heading, lines in (("Not matched", loadout.unmatched), ("Warnings", loadout.warnings)):
        if lines:
            blocks.append(_section(heading, "\n".join(
                '  <p class="warn">%s</p>' % _esc(x) for x in lines)))
    return ("\n" + "\n\n".join(blocks) + "\n") if blocks else ""


def _render_html(loadout: Loadout) -> str:
    sections, _ = _sections(loadout)
    if sections:
        body = "\n\n".join(_section(heading, "\n".join(_card(it) for it in items))
                           for heading, items in sections)
    else:
        body = _section("Loadout", '  <p class="empty">No items in this loadout.</p>')
    n = len(loadout.items)
    subtitle = ("%d import-ready code%s, re-leveled to %s. Paste each into the Item "
                "Builder's decoder box, Decode &amp; Validate, then Add to Backpack."
                % (n, "" if n == 1 else "s",
                   _esc(loadout.level) if loadout.level is not None else "their saved level"))
    title = _esc(loadout.title)
    return _PAGE % {"title": title, "css": CSS, "subtitle": subtitle, "body": body,
                    "notices": _notices(loadout), "js": COPY_JS}


# --------------------------------------------------------------------------------------------
# plain text
# --------------------------------------------------------------------------------------------
def _render_text(loadout: Loadout) -> str:
    title = _one_line(loadout.title)
    lines = [title, "=" * len(title), ""]
    if loadout.level is not None:
        lines.append("All codes re-leveled to %s." % _one_line(loadout.level))
        lines.append("")
    sections, grouped = _sections(loadout)
    for heading, items in sections:
        if grouped:
            lines.append("[%s]" % _one_line(heading))
        for it in items:
            el = _element(it.element)
            lines.append("%s%s" % (_one_line(it.shown_name or "?"), ("  (%s)" % _one_line(el[1])) if el else ""))
            lines.append("".join(_CONTROL.sub("", _s(it.serial)).split()))   # one serial, one line
            lines.append("")
    return "\n".join(lines)


# --------------------------------------------------------------------------------------------
# the module
# --------------------------------------------------------------------------------------------
class RenderModule(Module):
    name = "render"
    purpose = "Present a Loadout as a self-contained HTML code sheet and a plain-text list."
    requires = ()
    port = RenderPort

    def html(self, loadout: Loadout) -> str:
        return _render_html(loadout)

    def text(self, loadout: Loadout) -> str:
        return _render_text(loadout)

    def write(self, loadout: Loadout, html_path: str, text_path: Optional[str] = None) -> Tuple[str, str]:
        html_path = os.fspath(html_path)
        text_path = os.fspath(text_path) if text_path is not None else os.path.splitext(html_path)[0] + ".txt"
        if os.path.normcase(os.path.abspath(html_path)) == os.path.normcase(os.path.abspath(text_path)):
            raise ForgeError("html and text output would be the same file (%s); pass a distinct text_path"
                             % html_path)
        page, plain = self.html(loadout), self.text(loadout)   # render both before touching the disk
        for path, content in ((html_path, page), (text_path, plain)):
            try:
                parent = os.path.dirname(path)
                if parent:
                    os.makedirs(parent, exist_ok=True)
                with open(path, "w", encoding="utf-8", newline="\n") as f:
                    f.write(content)
            except OSError as ex:
                raise ForgeError("cannot write %s: %s" % (path, ex)) from ex
        return html_path, text_path

    # ---- health ----------------------------------------------------------------------------
    def health(self) -> HealthReport:
        """Render a one-item Loadout built in code and check the known answers. Never raises."""
        serial = "@Ugr$health-probe-0123456789"
        payload = '<script>alert("x")</script>'
        probe = Loadout(
            title="Health probe", level=60, groups=("Probe",),
            items=(LoadoutItem(name="Probe " + payload, serial=serial, level=60, group="Probe",
                               element="cryo", rarity="Legendary", note="a <em>b</em> " + payload),))
        checks: List[HealthCheck] = []

        def check(name: str, fn: Callable[[], str]) -> None:
            try:
                problem = fn()
            except Exception as ex:   # health() must never raise
                problem = "raised %s: %s" % (type(ex).__name__, ex)
            checks.append(HealthCheck(name, not problem, problem or ""))

        def html_check() -> str:
            page = self.html(probe)
            if _esc(serial) not in page:
                return "serial missing from html()"
            if page.count("<script") != 1:
                return "unexpected <script> count (payload not escaped?)"
            if "&lt;script&gt;" not in page or "<em>b</em>" not in page:
                return "escaping / <em> whitelist wrong"
            if 'class="badge cryo"' not in page or ">Cryo<" not in page:
                return "element badge missing"
            return ""

        def text_check() -> str:
            plain = self.text(probe)
            lines = plain.split("\n")
            if lines.count(serial) != 1:
                return "serial not on exactly one line of text()"
            if "[Probe]" not in lines or "<" in plain.replace(payload, ""):
                return "group heading missing or markup in text()"
            return ""

        def self_contained_check() -> str:
            page = self.html(probe).lower()
            for bad in ("http://", "https://", "<link", "src="):
                if bad in page:
                    return "found %r in html()" % bad
            return ""

        check("html_renders", html_check)
        check("text_renders", text_check)
        check("self_contained", self_contained_check)
        failed = [c for c in checks if not c.ok]
        summary = ("html + text render, escaping and self-containment verified" if not failed
                   else "%d of %d checks failed: %s" % (len(failed), len(checks), failed[0].detail))
        return HealthReport(ok=not failed, checks=tuple(checks), summary=summary)


MODULE = RenderModule
